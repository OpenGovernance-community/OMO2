CREATE TABLE IF NOT EXISTS performance_request (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 request_id CHAR(32) NOT NULL,
 parent_request_id CHAR(32) NOT NULL DEFAULT '',
 started_at DATETIME(6) NOT NULL,
 route VARCHAR(190) NOT NULL,
 method VARCHAR(8) NOT NULL,
 kind VARCHAR(8) NOT NULL DEFAULT 'web',
 IDorganization INT NOT NULL DEFAULT 0,
 IDuser INT NOT NULL DEFAULT 0,
 status_code SMALLINT NOT NULL DEFAULT 200,
 duration_ms DOUBLE NOT NULL DEFAULT 0,
 cpu_ms DOUBLE NULL,
 sql_ms DOUBLE NOT NULL DEFAULT 0,
 query_count INT UNSIGNED NOT NULL DEFAULT 0,
 sql_errors INT UNSIGNED NOT NULL DEFAULT 0,
 peak_memory BIGINT UNSIGNED NOT NULL DEFAULT 0,
 cron_state TINYINT NOT NULL DEFAULT 0,
 cron_calls INT UNSIGNED NOT NULL DEFAULT 0,
 cron_ms DOUBLE NOT NULL DEFAULT 0,
 aggregated TINYINT NOT NULL DEFAULT 0,
 KEY pending (aggregated, id),
 KEY retention (aggregated, started_at),
 KEY request_trace (request_id),
 KEY parent_trace (parent_request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

