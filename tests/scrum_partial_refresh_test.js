'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const fixture = JSON.parse(fs.readFileSync(path.join(__dirname, '../tmp/scrum-browser-fixture.json'), 'utf8'));
const source = fs.readFileSync(path.join(__dirname, '../omo/api/projects/projects.js'), 'utf8');
const flush = async () => { for (let i = 0; i < 8; i++) await new Promise(resolve => setImmediate(resolve)); };
(async () => {
    const dom = new JSDOM(fixture.running, {url: 'https://omo.test/omo/', runScripts: 'outside-only', pretendToBeVisual: true});
    const w = dom.window, d = w.document;
    w.resetGenericExpandedMenu = () => {};
    w.matchMedia = () => ({matches: true});
    w.requestAnimationFrame = callback => { callback(); return 1; };
    const viewport = d.querySelector('#omo-scrum-detail > .omo-panel-view__body');
    viewport.scrollTo = options => { viewport.scrollTop = options.top; };
    const errors = [], requests = [];
    let reloads = 0, nextHtml = fixture.moving, failPost = false, failGet = false, releaseGet;
    w.omoNotify = message => errors.push(message);
    w.omoReplaceFetchedPanelRoot = () => { reloads++; return Promise.resolve(); };
    w.fetch = async (url, options) => {
        requests.push({url, options});
        if (options.method === 'POST') return {ok: !failPost, text: async () => JSON.stringify({success: !failPost, message: 'Rejected'})};
        if (failGet) throw new Error('Refresh failed');
        return new Promise(resolve => { releaseGet = () => resolve({ok: true, text: async () => nextHtml}); });
    };
    w.eval(source);
    const root = d.querySelector('#omo-projects-root'), detail = d.querySelector('#omo-scrum-detail');
    const header = detail.querySelector('header'), summary = detail.querySelector('[data-scrum-summary]');
    const initialGraph = summary.querySelector('svg');
    const columns = Array.from(root.querySelectorAll('[data-omo-projects-column]'));
    const parent = root.querySelector('[data-omo-project-card][data-project-id="' + fixture.parent + '"]');
    const getChild = () => root.querySelector('[data-omo-project-card][data-project-id="' + fixture.child + '"]');
    const choose = status => {
        const select = getChild().querySelector('[data-omo-project-status-select]');
        select.value = status;
        select.dispatchEvent(new w.Event('change', {bubbles: true}));
    };
    choose('in_progress'); await flush();
    assert.equal(getChild().closest('[data-omo-projects-cards]').dataset.status, 'in_progress', 'Saved move leaves source before refresh arrives');
    assert.equal(root.querySelector('[data-omo-projects-column="ready"] [data-omo-projects-column-count]').textContent, '1');
    releaseGet(); await flush();
    assert.equal(d.querySelector('#omo-scrum-detail'), detail);
    assert.equal(detail.querySelector('header'), header);
    assert.equal(root.querySelector('[data-project-id="' + fixture.parent + '"]'), parent, 'Other source cards stay intact');
    assert.deepEqual(Array.from(root.querySelectorAll('[data-omo-projects-column]')), columns, 'Column containers remain in place');
    assert.notEqual(summary.querySelector('svg'), initialGraph, 'Only summary content is refreshed');
    assert.equal(root.querySelector('.is-mobile-active').dataset.omoProjectsColumn, 'in_progress', 'Destination is selected on mobile');
    assert.equal(getChild().getAttribute('data-project-status'), 'in_progress');
    // Newly rendered cards must still support drag and drop.
    nextHtml = fixture.reviewed;
    let draggedId;
    const transfer = {setData: (type, value) => { draggedId = value; }, getData: () => draggedId};
    const drag = new w.Event('dragstart', {bubbles: true}); Object.defineProperty(drag, 'dataTransfer', {value: transfer});
    getChild().dispatchEvent(drag);
    assert.equal(draggedId, String(fixture.child));
    const drop = new w.Event('drop', {bubbles: true, cancelable: true}); Object.defineProperty(drop, 'dataTransfer', {value: transfer});
    root.querySelector('[data-omo-projects-cards="review"]').dispatchEvent(drop);
    await flush(); releaseGet(); await flush();
    assert.equal(getChild().getAttribute('data-project-status'), 'review');
    assert.match(summary.textContent, /Restant : 0 %/);
    assert.equal(root.querySelector('[data-omo-projects-column="in_progress"] [data-omo-projects-column-count]').textContent, '0');
    assert.ok(root.querySelector('[data-omo-projects-cards="in_progress"] [data-omo-projects-column-empty]'));
    failPost = true; choose('ready'); await flush();
    assert.equal(getChild().getAttribute('data-project-status'), 'review', 'Rejected mutation keeps source intact');
    assert.equal(getChild().querySelector('select').value, 'review');
    assert.equal(errors.pop(), 'Rejected');
    failPost = false; failGet = true; choose('in_progress'); await flush();
    assert.equal(getChild().getAttribute('data-project-status'), 'in_progress', 'Refresh failure never rolls back a saved move');
    assert.equal(getChild().querySelector('select').value, 'in_progress');
    assert.equal(errors.pop(), 'Refresh failed');
    assert.equal(reloads, 0, 'No full panel reload, including on errors');
    assert.equal(root.querySelector('[aria-busy="true"]'), null);
    assert.equal(requests.filter(request => request.options.method === 'POST').length, 4, 'No duplicated mutation handlers after refresh');
    dom.window.close();
    console.log('Scrum partial refresh: moves, drag rebind, summary, counters, mobile destination and failure handling passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
