'use strict';
const assert = require('node:assert/strict');
const {spawn} = require('node:child_process');
const {createInterface} = require('node:readline');
const {chromium} = require(process.argv[2] || 'playwright');
(async () => {
    const fixture = spawn('docker', ['compose', 'exec', '-T', 'app', 'php', '-d', 'display_errors=1', 'tests/public_quiz_browser_fixture.php'], {stdio: ['pipe', 'pipe', 'inherit']});
    const closed = new Promise(resolve => fixture.on('close', resolve));
    const lines = createInterface({input: fixture.stdout});
    let browser;
    try {
        const c = JSON.parse((await lines[Symbol.asyncIterator]().next()).value);
        browser = await chromium.launch({headless: true, channel: 'chrome'});
        const context = await browser.newContext({ignoreHTTPSErrors: true, viewport: {width: 1000, height: 850}, extraHTTPHeaders: {Origin: c.origin}});
        await context.addInitScript(() => { window.turnstile = {ready: cb => cb(), render: () => 'fixture', reset() {}, remove() {}}; });
        await context.route('https://player.vimeo.com/api/player.js', route => route.fulfill({contentType: 'text/javascript', body: ''}));
        // Isolate quiz completion from the unrelated old local mission-list schema.
        await context.route('**/getmissions.php?*', route => {
            const done = new URL(route.request().url()).searchParams.get('done_ids');
            return route.fulfill({contentType: 'application/json', body: JSON.stringify({html: '', progress: done ? 100 : 0})});
        });
        const endpoint = c.origin + '/omo/api/lms/checkAnswer.php?catalog=basic';
        const base = {parcours_id: c.pid, mission_id: c.mid, question_id: c.questions.single.id, choices: c.questions.single.correct};
        const check = async (data, status, correct) => {
            const response = await context.request.post(endpoint, {data});
            assert.equal(response.status(), status, await response.text());
            const payload = await response.json();
            assert.equal(payload.correct, correct);
            if (!correct) assert(!Object.hasOwn(payload, 'answer'), 'Explanations are not sent before a correct answer.');
            else assert.equal(payload.answer, Object.values(c.questions).find(question => question.id === data.question_id).answer);
        };
        await check(base, 200, true);
        await check({...base, choices: c.questions.single.wrong}, 200, false);
        await check({...base, choices: c.questions.private.correct}, 200, false);
        await check({...base, question_id: c.questions.multiple.id, choices: c.questions.multiple.correct}, 200, true);
        await check({...base, question_id: c.questions.multiple.id, choices: c.questions.multiple.correct.slice(0, 1)}, 200, false);
        await check({...base, question_id: c.questions.private.id, choices: c.questions.private.correct}, 404, false);
        await check({...base, mission_id: c.privateMid}, 404, false);
        await check({...base, parcours_id: c.privatePid, mission_id: c.privateMid, question_id: c.questions.private.id, choices: c.questions.private.correct}, 401, false);
        await check({...base, choices: [[]]}, 400, false);
        await check({...base, question_id: null}, 400, false);
        assert.equal((await context.request.get(endpoint)).status(), 405);
        assert.equal((await context.request.post(c.origin + '/omo/api/lms/checkAnswer.php', {data: base})).status(), 401);
        const legacy = await context.request.post(`${c.origin}/lms/checkAnswer.php?oid=${c.oid}`, {data: base});
        assert.equal(legacy.status(), 200);
        assert.equal((await legacy.json()).correct, true);
        const questions = await (await context.request.get(`${c.origin}/omo/api/lms/getMissionQuestions.php?catalog=basic&parcours_id=${c.pid}&mission_id=${c.mid}`)).json();
        assert.equal(questions.length, 2);
        assert(!JSON.stringify(questions).includes('is_correct'));
        assert(questions.every(question => !Object.hasOwn(question, 'answer')), 'Question listing does not disclose explanations in advance.');
        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        const publicUrl = `${c.origin}/omo/api/lms/parcours.php?catalog=basic&idp=${c.pid}&mid=${c.mid}`;
        await page.goto(publicUrl);
        await page.locator('#doneBtn').filter({hasText: 'Commencer'}).waitFor();
        assert.equal(await page.evaluate(() => typeof window.commonNotify), 'function');
        await page.locator('#doneBtn').click();
        await page.locator(`input[name="qcm"][value="${c.questions.single.wrong[0]}"]`).check();
        await page.locator('#doneBtn').click();
        await page.locator('.common-notification').filter({hasText: 'Mauvaise'}).waitFor();
        const storageKey = `lms_progress_0_${c.pid}`;
        assert.equal(await page.evaluate(key => localStorage.getItem(key), storageKey), null);
        // Network failures preserve the chosen answer and permit a retry.
        await page.locator(`input[name="qcm"][value="${c.questions.single.correct[0]}"]`).check();
        await page.route('**/checkAnswer.php?catalog=basic', route => route.fulfill({status: 503, contentType: 'application/json', body: '{"correct":false}'}), {times: 1});
        await page.locator('#doneBtn').click();
        await page.locator('.common-notification').filter({hasText: 'Reessayez'}).waitFor();
        assert(await page.locator(`input[value="${c.questions.single.correct[0]}"]`).isChecked());
        assert(await page.locator('#doneBtn').isEnabled());
        const sent = page.waitForRequest(request => request.url().includes('/checkAnswer.php') && request.method() === 'POST');
        await page.locator('#doneBtn').click();
        const request = await sent;
        assert.equal(new URL(request.url()).searchParams.get('catalog'), 'basic');
        assert.equal(request.postDataJSON().question_id, c.questions.single.id);
        const feedback = page.locator('[data-lms-quiz-feedback]');
        await feedback.waitFor();
        assert.equal(await feedback.locator('strong').textContent(), 'Bien joué');
        assert.equal(await feedback.locator('p').textContent(), c.questions.single.answer.replace('\n', ''));
        assert.equal(await feedback.locator('p strong').count(), 0, 'Explanation text is displayed safely without interpreting HTML.');
        assert.equal(await page.locator('#doneBtn').textContent(), 'Suivant');
        assert.equal(await page.locator('#drawer-footer button:visible').count(), 1, 'Only the feedback continuation action is shown.');
        assert.equal(await page.locator('input[name="qcm"]').count(), 0);
        assert.equal(await page.evaluate(key => localStorage.getItem(key), storageKey), null);
        await page.locator('#doneBtn').click();
        for (const choice of c.questions.multiple.correct) await page.locator(`input[name="qcm"][value="${choice}"]`).check();
        await page.locator('#doneBtn').click();
        await feedback.filter({hasText: 'Final educational explanation.'}).waitFor();
        assert.equal(await page.locator('#doneBtn').textContent(), 'Fermer');
        assert.equal(await page.locator('#drawer-footer button:visible').count(), 1, 'The final close button validates the mission.');
        assert.equal(await page.evaluate(key => localStorage.getItem(key), storageKey), null, 'Completion waits until the last explanation is closed.');
        await page.setViewportSize({width: 390, height: 700});
        await page.screenshot({path: 'tmp/public-quiz-feedback-mobile.png'});
        const closeBox = await page.locator('#doneBtn').boundingBox();
        assert(closeBox.y >= 0 && closeBox.y + closeBox.height <= 700, 'Close remains reachable with a long explanation on mobile.');
        assert(await page.locator('#quiz-zone').evaluate(el => el.scrollHeight > el.clientHeight), 'Long explanations can scroll.');
        await page.locator('#doneBtn').click();
        await page.waitForFunction(({key, mid}) => !!JSON.parse(localStorage.getItem(key) || '{}').missions?.[mid], {key: storageKey, mid: c.mid});
        await page.waitForFunction(() => document.getElementById('progressPercent').textContent === '100 %');
        assert.equal(await page.locator('#progressPercent').textContent(), '100 %');
        await page.reload();
        await page.waitForFunction(() => document.getElementById('progressPercent').textContent === '100 %');
        assert(await page.evaluate(({key, mid}) => !!JSON.parse(localStorage.getItem(key)).missions[mid], {key: storageKey, mid: c.mid}));
        assert.deepEqual(errors, []);
        // Blank explanations keep direct progression, including on the final question.
        await page.evaluate(key => localStorage.removeItem(key), storageKey);
        await page.route('**/checkAnswer.php?catalog=basic', async route => {
            const response = await route.fetch();
            const payload = await response.json();
            if (payload.correct) payload.answer = '  \n ';
            await route.fulfill({response, json: payload});
        });
        await page.goto(publicUrl);
        await page.locator('#doneBtn').filter({hasText: 'Commencer'}).click();
        await page.locator(`input[name="qcm"][value="${c.questions.single.correct[0]}"]`).check();
        await page.locator('#doneBtn').click();
        for (const choice of c.questions.multiple.correct) await page.locator(`input[name="qcm"][value="${choice}"]`).check();
        assert.equal(await feedback.count(), 0);
        await page.locator('#doneBtn').click();
        await page.waitForFunction(({key, mid}) => !!JSON.parse(localStorage.getItem(key) || '{}').missions?.[mid], {key: storageKey, mid: c.mid});
        assert.deepEqual(errors, []);
        // The OMO tutorial iframe has no topbar and must render notifications locally.
        const parent = await context.newPage();
        parent.on('pageerror', error => errors.push(error.message));
        await parent.setViewportSize({width: 1100, height: 800});
        const parentUrl = c.origin + '/omo/quiz-notification-fixture';
        await parent.route(parentUrl, route => route.fulfill({contentType: 'text/html', body:
            `<style>body{margin:0}iframe{position:fixed;inset:70px 20px 20px;width:calc(100% - 40px);height:calc(100% - 90px);border:0}</style><iframe src="${publicUrl}&embed=1"></iframe>`}));
        await parent.goto(parentUrl);
        const frame = parent.frames().find(frame => frame !== parent.mainFrame());
        await frame.locator('#doneBtn').filter({hasText: 'Commencer'}).waitFor();
        assert.equal(await frame.locator('.common-topbar').count(), 0);
        assert.equal(await parent.evaluate(() => typeof window.commonNotify), 'undefined');
        assert.equal(await frame.evaluate(() => typeof window.commonNotify), 'function');
        assert.equal(await frame.evaluate(() => typeof window.omoNotify), 'function');
        await frame.evaluate(() => { window.quizAlertCount = 0; window.alert = () => { window.quizAlertCount++; }; });
        await frame.locator('#doneBtn').click();
        await frame.locator(`input[name="qcm"][value="${c.questions.single.wrong[0]}"]`).check();
        await frame.locator('#doneBtn').click();
        const wrongNotice = frame.locator('.common-notification').filter({hasText: 'Mauvaise'});
        await wrongNotice.waitFor();
        assert(await wrongNotice.evaluate(el => {
            const box = el.getBoundingClientRect();
            return !!document.elementFromPoint(box.x + 20, box.y + 20)?.closest('.common-notification');
        }), 'The notification is above the quiz drawer inside the iframe.');
        assert.equal(await frame.locator('.common-notifications').evaluate(el => getComputedStyle(el).position), 'fixed');
        assert.equal(await parent.locator('#commonNotifications').count(), 0, 'The parent page is not needed to show the message.');
        await frame.locator(`input[name="qcm"][value="${c.questions.single.correct[0]}"]`).check();
        await parent.route('**/checkAnswer.php?catalog=basic', route => route.fulfill({status: 503, contentType: 'application/json', body: '{"correct":false}'}), {times: 1});
        await frame.locator('#doneBtn').click();
        await frame.locator('.common-notification').filter({hasText: 'Reessayez'}).waitFor();
        assert.equal(await frame.evaluate(() => window.quizAlertCount), 0);
        await parent.screenshot({path: 'tmp/public-quiz-iframe-notifications.png'});
        // Compatibility wrapper keeps options such as automatic dismissal duration.
        const transientId = await frame.evaluate(() => window.omoNotify('Transient frame notice', 'error', {duration: 50}));
        await frame.locator('[id="' + transientId + '"]').waitFor({state: 'detached'});
        await frame.goto(c.origin + '/omo/api/lms/?catalog=basic&embed=1');
        await frame.evaluate(() => window.omoNotify('Catalog frame error', 'error'));
        await frame.locator('.common-notification').filter({hasText: 'Catalog frame error'}).waitFor();
        assert.deepEqual(errors, []);
        console.log('PASS public quiz, explanations, local progress and visible iframe-local quiz/catalog notifications');
    } finally {
        if (browser) await browser.close();
        fixture.stdin.end('\n');
        assert.equal(await closed, 0, 'Quiz fixtures removed and anonymous server progress unchanged');
        lines.close();
    }
})().catch(error => {console.error(error); process.exitCode = 1;});
