const assert = require('node:assert/strict');
const {spawn} = require('node:child_process');
const {createInterface} = require('node:readline');
const {chromium} = require(process.argv[2] || 'playwright');

(async () => {
    const fixture = spawn('docker', ['compose', 'exec', '-T', 'app', 'php', 'tests/server_env_infomaniak_browser_fixture.php'], {stdio: ['pipe', 'pipe', 'inherit']});
    const closed = new Promise(resolve => fixture.on('close', resolve));
    let browser;
    try {
        const first = await createInterface({input: fixture.stdout})[Symbol.asyncIterator]().next();
        assert(!first.done, 'Local fixture starts');
        const config = JSON.parse(first.value);
        console.log('Checking Infomaniak endpoint access');
        browser = await chromium.launch({headless: true, channel: 'chrome', args: ['--host-resolver-rules=MAP localtest.me 127.0.0.1, MAP *.localtest.me 127.0.0.1']});
        const context = await browser.newContext({ignoreHTTPSErrors: true, extraHTTPHeaders: {Origin: config.origin}, viewport: {width: 1100, height: 900}});
        context.setDefaultTimeout(15000);
        await context.addInitScript(() => { window.turnstile = {ready: callback => callback(), render: () => 'fixture', reset() {}, remove() {}}; });
        const endpoint = config.origin + '/omo/api/parameters/server_env_infomaniak.php';
        const anonymous = await browser.newContext({ignoreHTTPSErrors: true, extraHTTPHeaders: {Origin: config.origin}});
        assert.equal((await anonymous.request.post(endpoint, {form: {}})).status(), 401, 'Anonymous discovery denied');
        await anonymous.close();
        const login = await context.request.post(config.origin + '/common/login_password.php', {form: {email: config.email, password: config.password}, headers: {'X-Requested-With': 'XMLHttpRequest'}});
        assert.equal((await login.json()).status, 'ok');
        assert.equal((await context.request.post(endpoint, {form: {}})).status(), 403, 'Site admin mode required');
        await context.request.post(config.origin + '/common/site_admin_mode.php', {form: {enabled: '1'}, headers: {'X-Requested-With': 'XMLHttpRequest'}});
        assert.equal((await context.request.post(endpoint, {form: {}})).status(), 423, 'Password unlock required');
        assert.equal((await context.request.get(endpoint)).status(), 405, 'GET cannot invoke discovery');
        const unlock = await context.request.post(config.origin + '/omo/api/parameters/server_env_unlock.php', {form: {password: config.password}});
        assert.equal((await unlock.json()).status, true, 'Settings unlocked');
        assert.equal((await context.request.post(endpoint, {form: {}, headers: {Origin: 'https://other.invalid'}})).status(), 403, 'Cross-origin discovery denied');
        const invalid = await context.request.post(endpoint, {form: {token: 'invalid token with whitespace'}});
        assert.equal(invalid.status(), 422);
        const invalidBody = await invalid.json();
        assert(!invalidBody.message.includes('invalid token with whitespace'), 'Token never reflected in error');
        assert(invalidBody.message.includes('espaces ou des retours'), 'Format errors explain that no API request was made');
        const unverified = await context.request.post(config.origin + '/omo/api/parameters/server_env_save.php', {form: {
            AI_PROVIDER: 'infomaniak', AI_API_KEY: 'fixture-token', AI_INFOMANIAK_PRODUCT_ID: '123', AI_MODEL: 'mistral-small', AI_TRANSLATION_MODEL: ''
        }});
        assert.equal(unverified.status(), 422, 'Server refuses a configuration that bypasses discovery');
        console.log('Checking Infomaniak settings controls');

        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(config.origin + '/omo/o/' + config.oid, {waitUntil: 'domcontentloaded', timeout: 45000});
        await page.waitForFunction(() => typeof window.commonTopbarOpenModal === 'function');
        await page.evaluate(() => window.commonTopbarOpenModal('Admin du serveur', '/omo/api/parameters/server_env_popup.php', 'fetch'));
        await page.locator('#omoServerEnvForm').waitFor();
        await page.evaluate(() => {
            window.testNotifications = [];
            const notify = window.commonNotify;
            window.commonNotify = (message, type, options) => {
                window.testNotifications.push({message, type});
                return notify(message, type, options);
            };
        });
        await page.locator('[data-generic-tab-target="omoServerEnvPanel-ai"]').click();
        const provider = page.locator('[name="AI_PROVIDER"]');
        const main = () => page.locator('[name="AI_MODEL"]');
        const translation = () => page.locator('[name="AI_TRANSLATION_MODEL"]');
        const product = page.locator('[name="AI_INFOMANIAK_PRODUCT_ID"]');
        const token = page.locator('[name="AI_API_KEY"]');
        const load = page.locator('#omoServerEnvInfomaniakLoad');
        if (process.argv.includes('--live')) {
            assert.equal(await provider.inputValue(), 'infomaniak', 'Live test requires the saved Infomaniak provider');
            assert.equal(await token.inputValue(), '', 'Saved token remains masked and absent from the form');
            assert(await product.inputValue(), 'Live test requires a saved product');
            const responseReady = page.waitForResponse(response => response.url().endsWith('/server_env_infomaniak.php'));
            await load.click();
            const liveResponse = await responseReady;
            const live = await liveResponse.json();
            assert.equal(live.status, true, live.message);
            assert(live.models.length > 0, 'Saved token loads real Infomaniak models with an empty password field');
            assert.equal(await token.inputValue(), '', 'Discovery never fills the password field');
            console.log(`PASS live Infomaniak discovery with saved token: ${live.models.length} models`);
        }
        const audioProvider = page.locator('[name="TRANSCRIPTION_PROVIDER"]');
        const audioModel = () => page.locator('[name="TRANSCRIPTION_MODEL"]');
        const audioProduct = page.locator('[name="TRANSCRIPTION_INFOMANIAK_PRODUCT_ID"]');
        await audioProvider.selectOption('openai');
        await audioModel().fill('gpt-4o-mini-transcribe');
        await audioProvider.selectOption('infomaniak');
        assert.equal(await audioModel().evaluate(node => node.tagName), 'SELECT');
        assert.equal(await audioModel().inputValue(), 'whisper', 'Whisper V3 selected automatically for Infomaniak audio');
        assert(await audioProduct.isVisible(), 'Infomaniak audio has its own Product ID input');
        await audioProduct.fill('456');
        await provider.selectOption('anthropic');
        assert.equal(await audioProvider.inputValue(), 'infomaniak', 'Audio provider stays independent of text');
        assert.equal(await audioProduct.inputValue(), '456', 'Audio product is retained when text changes');
        assert.equal(await audioModel().inputValue(), 'whisper');
        await audioProduct.fill('');
        await audioProvider.selectOption('openai');
        assert.equal(await audioModel().evaluate(node => node.tagName), 'INPUT');
        assert.equal(await audioModel().inputValue(), 'gpt-4o-mini-transcribe', 'Switching audio back restores its provider default');
        assert.equal(await audioProduct.isVisible(), false);
        // Use an independent baseline so this suite also works with Infomaniak already configured.
        await provider.selectOption('mistral');
        await main().fill('fixture-other-model');
        const originalProvider = await provider.inputValue();
        const originalModel = await main().inputValue();
        await provider.selectOption('infomaniak');
        assert(await load.isVisible(), 'Refresh button is visible in the real OMO modal');
        assert(await load.evaluate(node => !!node.closest('.generic-form-field').querySelector('[name="AI_API_KEY"]')), 'Refresh button is next to the token');
        assert.equal(await main().evaluate(node => node.tagName), 'SELECT');
        assert.notEqual(await main().inputValue(), 'fixture-other-model', 'Other provider model is not reused');
        assert(await page.locator('[name="AI_BASE_URL"]').isDisabled());
        let scenario = 'multiple';
        let requested = [];
        const products = [{id: '123', label: 'AI Services - Organization A (#123)'}, {id: '456', label: 'AI Services - Organization B (#456)'}];
        await page.route('**/server_env_infomaniak.php', async route => {
            const body = route.request().postData() || '';
            requested.push(body);
            if (scenario === 'failure') return route.fulfill({status: 422, json: {status: false, message: 'Temporary API failure'}});
            if (scenario === 'html') return route.fulfill({status: 502, contentType: 'text/html', body: '<html>Bad gateway</html>'});
            if (scenario === 'invalid-json') return route.fulfill({status: 200, contentType: 'text/html', body: '<html>Login required</html>'});
            if (scenario === 'locked') return route.fulfill({status: 423, json: {status: false, requiresUnlock: true}});
            if (scenario === 'network') return route.abort('failed');
            if (scenario === 'timeout') return;
            if (scenario === 'slow') await new Promise(resolve => setTimeout(resolve, 300));
            const selected = body.match(/name="productId"\r\n\r\n([^\r]*)/)?.[1] || '';
            const id = scenario === 'single' || scenario === 'slow' ? '123' : selected;
            const available = scenario === 'replacement' ? [products[1], {id: '789', label: 'AI Services - Organization C (#789)'}] : products;
            await route.fulfill({json: {status: true, products: scenario === 'single' ? products.slice(0, 1) : available, productId: id,
                models: id ? [{id: 'mistral-small', label: 'Mistral Small'}, {id: 'ministral', label: 'Ministral'}] : []}});
        });
        await token.fill('fixture-token');
        await product.fill('');
        await load.click();
        assert.equal(await product.getAttribute('type'), 'text', 'Product ID can be entered manually');
        await page.waitForFunction(() => document.querySelector('#omoServerEnvInfomaniakProducts').options.length === 2);
        assert.equal(await product.inputValue(), '', 'Several products require selection');
        await product.fill('123');
        await load.click();
        await page.waitForFunction(() => document.querySelector('[name="AI_MODEL"]').options.length === 3);
        await main().selectOption('mistral-small');
        await translation().selectOption('ministral');
        assert(requested.every(body => body.includes('fixture-token')), 'Unsaved token is sent only to same-origin discovery');
        await provider.selectOption(originalProvider);
        assert.equal(await main().evaluate(node => node.tagName), 'INPUT');
        assert.equal(await main().inputValue(), originalModel, 'Returning to the original provider restores its model');
        await provider.selectOption('infomaniak');
        assert.equal(await main().inputValue(), 'mistral-small');
        scenario = 'single';
        await product.fill('');
        await load.click();
        await page.waitForFunction(() => document.querySelector('#omoServerEnvInfomaniakProducts').options.length === 1);
        assert.equal(await product.inputValue(), '123', 'Single product selected automatically');
        assert.equal(await main().inputValue(), 'mistral-small', 'Refresh preserves valid selections');
        scenario = 'multiple';
        await load.click();
        await page.waitForFunction(() => document.querySelector('#omoServerEnvInfomaniakProducts').options.length === 2 && !document.querySelector('#omoServerEnvInfomaniakLoad').disabled);
        assert.equal(await product.inputValue(), '123', 'Refreshing several products keeps an authorized current product');
        assert.equal(await main().inputValue(), 'mistral-small');
        scenario = 'replacement';
        await product.fill('');
        await load.click();
        await page.waitForFunction(() => document.querySelector('[name="AI_INFOMANIAK_PRODUCT_ID"]').value === '' && !document.querySelector('#omoServerEnvInfomaniakLoad').disabled);
        assert.equal(await page.locator('#omoServerEnvInfomaniakProducts option[value="123"]').count(), 0, 'Suggestions follow the discovered products');
        await product.fill('456');
        await load.click();
        await page.waitForFunction(() => document.querySelector('[name="AI_MODEL"]').options.length === 3);
        await main().selectOption('mistral-small');
        await translation().selectOption('ministral');
        scenario = 'failure';
        await load.click();
        await page.waitForFunction(() => window.testNotifications.some(item => item.message === 'Temporary API failure'));
        assert.equal(await main().inputValue(), 'mistral-small', 'API outage preserves selected settings');
        assert.equal(await page.locator('#omoServerEnvInfomaniakFeedback').textContent(), '', 'No duplicate inline notification');
        for (const [kind, match] of [['html', 'HTTP 502'], ['invalid-json', 'reponse inattendue'], ['network', 'connexion avec le serveur OMO'], ['locked', 'deverrouillage des reglages a expire']]) {
            scenario = kind;
            const before = await page.evaluate(() => window.testNotifications.length);
            await load.click();
            await page.waitForFunction(count => window.testNotifications.length > count, before);
            const message = await page.evaluate(() => window.testNotifications.at(-1));
            assert(message.message.includes(match), `${kind}: ${message.message}`);
            assert.equal(message.type, 'error');
            assert.equal(await token.inputValue(), 'fixture-token', 'Failure retains unsaved token');
            assert.equal(await main().inputValue(), 'mistral-small', 'Failure retains selected model');
            assert.equal(await load.isDisabled(), false, 'Refresh remains available for retry');
        }
        await page.clock.install();
        scenario = 'timeout';
        await load.click();
        assert.equal(await load.getAttribute('aria-busy'), 'true');
        assert((await load.textContent()).includes('Chargement'));
        await page.clock.fastForward(46000);
        await page.waitForFunction(() => window.testNotifications.at(-1).message.includes('delai d attente'));
        assert.equal(await load.isDisabled(), false, 'Timed out loading restores refresh button');
        await page.clock.resume();
        scenario = 'slow';
        await load.click();
        await token.fill('replacement-token');
        await page.waitForTimeout(500);
        assert.equal(await main().inputValue(), 'mistral-small', 'Late results cannot overwrite selections after token change');
        assert.equal(await load.isDisabled(), false);
        scenario = 'single';
        await product.fill('');
        await load.click();
        await page.waitForFunction(() => document.querySelector('[name="AI_INFOMANIAK_PRODUCT_ID"]').value === '123' && !document.querySelector('#omoServerEnvInfomaniakLoad').disabled);
        let submitted;
        let saveAccepted = false;
        await page.route('**/server_env_save.php', async route => {
            submitted = route.request().postData();
            await route.fulfill({status: saveAccepted ? 200 : 422, json: {status: saveAccepted, message: saveAccepted ? 'Fixture saved' : 'Fixture rejected', configuredSecrets: {AI_API_KEY: true}}});
        });
        const dirty = () => page.evaluate(() => window.commonDrawerHasUnsavedChanges(document.getElementById('omoServerEnvForm')));
        assert.equal(await dirty(), true, 'Edited settings are protected before saving');
        await page.locator('#omoServerEnvSubmit').click();
        await page.waitForFunction(() => window.testNotifications.some(item => item.message === 'Fixture rejected'));
        assert.equal(await dirty(), true, 'Failed save must retain unsaved-change protection');
        saveAccepted = true;
        await page.locator('#omoServerEnvSubmit').click();
        await page.waitForFunction(() => window.testNotifications.some(item => item.message === 'Fixture saved'));
        assert(submitted.includes('AI_INFOMANIAK_PRODUCT_ID') && submitted.includes('mistral-small'), 'Selected configuration reaches save payload');
        assert.equal(await token.inputValue(), '', 'Secret field cleared after save');
        assert.equal(await dirty(), false, 'Successful save resets the guard after clearing secret fields');
        await load.click();
        await page.waitForFunction(() => !document.querySelector('#omoServerEnvInfomaniakLoad').disabled);
        assert.equal(requested.at(-1).match(/name="token"\r\n\r\n([^\r]*)/)?.[1], '', 'Refresh with a saved key sends no token to be re-entered');
        assert.equal(await dirty(), false, 'Refreshing unchanged selections does not mark the form dirty');
        await page.screenshot({path: 'tmp/infomaniak-settings-desktop.png', fullPage: true});
        await page.setViewportSize({width: 390, height: 844});
        await page.screenshot({path: 'tmp/infomaniak-settings-mobile.png', fullPage: true});
        const title = page.locator('[name="SITE_TITLE"]');
        const savedTitle = await title.inputValue();
        await title.fill(savedTitle + ' edited');
        assert.equal(await dirty(), true, 'New changes after saving remain protected');
        let dialogCount = 0;
        const dismiss = async dialog => { dialogCount++; await dialog.dismiss(); };
        page.on('dialog', dismiss);
        await page.locator('#commonTopbarModal button[data-topbar-modal-close]').click();
        assert.equal(dialogCount, 1, 'Closing with new unsaved data asks for confirmation');
        assert(await page.locator('#omoServerEnvForm').isVisible());
        await title.fill(savedTitle);
        assert.equal(await dirty(), false, 'Restoring the saved value clears unsaved changes');
        await page.locator('#commonTopbarModal button[data-topbar-modal-close]').click();
        assert.equal(dialogCount, 1, 'Closing saved data needs no loss-of-data warning');
        assert.equal(await page.locator('#commonTopbarModal').isVisible(), false);
        page.off('dialog', dismiss);
        assert.equal(errors.length, 0, errors.join('\n'));
        console.log('PASS Infomaniak admin/unlock/CSRF protection, dynamic model selects, product selection, refresh, errors and stale requests (simulated provider; no real settings saved)');
    } finally {
        if (browser) await browser.close();
        fixture.stdin.end('\n');
        await closed;
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
