'use strict';
// Run scrum_http_test.php first, then run with jsdom on NODE_PATH.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const fixture = JSON.parse(fs.readFileSync(path.join(__dirname, '../tmp/scrum-browser-fixture.json'), 'utf8'));
const source = fs.readFileSync(path.join(__dirname, '../omo/api/scrum/scrum.js'), 'utf8');
const pickerSource = fs.readFileSync(path.join(__dirname, '../common/project-picker/project-picker.js'), 'utf8');

async function main() {
    const dom = new JSDOM(fixture.picker, {url: 'https://omo.test/omo/', runScripts: 'outside-only'});
    const {window} = dom; const {document} = window; const requests = []; const navigation = [];
    window.omoNotify = () => {};
    let modalClosed = 0;
    window.commonTopbarCloseModal = () => { modalClosed++; };
    const parentDetail = document.createElement('div'); parentDetail.id = 'omo-scrum-detail';
    parentDetail.omoRefreshSprint = url => { navigation.push({rootSelector: '#omo-scrum-detail', url}); return Promise.resolve(); };
    document.body.appendChild(parentDetail);
    window.omoReplaceFetchedPanelRoot = options => { navigation.push(options); return Promise.resolve(options.currentRoot); };
    window.omoMountHolonScopePicker = () => ({matches: () => true, getSelectedHolonId: () => 0, destroy: () => {}});
    window.fetch = async (url, options) => { requests.push({url, options}); return {json: async () => ({status: true, message: 'Saved', url: '/omo/api/scrum/index.php?id=1'})}; };
    window.eval(pickerSource); window.eval(source);
    const select = document.querySelector('[data-scrum-select]');
    select.value = String(fixture.parent); select.dispatchEvent(new window.Event('change', {bubbles: true}));
    const preview = document.querySelector('[data-scrum-preview]');
    assert.equal(preview.querySelectorAll('select').length, 2, 'Picking a parent includes all children');
    assert.equal(document.querySelector('[data-scrum-step="sizes"]').hidden, true, 'Sizes are a separate second step');
    document.querySelector('[data-scrum-next]').click();
    assert.equal(document.querySelector('[data-scrum-step="selection"]').hidden, true);
    assert.equal(document.querySelector('[data-scrum-step="sizes"]').hidden, false);
    assert.match(document.querySelector('[data-scrum-total]').textContent, /2/);
    const parentSize = preview.querySelector('[data-project-id="' + fixture.parent + '"]');
    parentSize.value = 'XXL'; parentSize.dispatchEvent(new window.Event('change', {bubbles: true}));
    assert.equal(preview.querySelector('[data-project-id="' + fixture.parent + '"]').value, 'XXL');
    document.querySelector('[data-scrum-previous]').click();
    assert.equal(document.querySelector('[data-scrum-step="selection"]').hidden, false);
    document.querySelector('[data-scrum-next]').click();
    assert.equal(preview.querySelector('[data-project-id="' + fixture.parent + '"]').value, 'XXL', 'Back/next preserves adjusted sizes');
    const changedSize = preview.querySelector('[data-project-id="' + fixture.parent + '"]');
    changedSize.value = 'S'; changedSize.dispatchEvent(new window.Event('change', {bubbles: true}));

    assert.ok(preview.querySelector('small'), 'Underestimation must be explained inline');
    document.querySelector('[data-scrum-import]').click();
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(requests.length, 1);
    assert.equal(requests[0].options.body.get('action'), 'import');
    assert.equal(requests[0].options.body.get('sizes[' + fixture.parent + ']'), 'S');
    assert.equal(requests[0].options.body.get('sizes[' + fixture.child + ']'), 'M');
    assert.equal(navigation[0].rootSelector, '#omo-scrum-detail');
    assert.equal(modalClosed, 1, 'Successful import closes the popup and refreshes the detail');
    dom.window.close();

    const estimatesDom = new JSDOM(fixture.estimates, {url: 'https://omo.test/omo/', runScripts: 'outside-only'});
    const ew = estimatesDom.window; const ed = ew.document; const estimateRequests = [];
    ew.omoNotify = () => {};
    ew.commonTopbarCloseModal = () => {};
    ew.fetch = async (url, options) => { estimateRequests.push(options.body); return {json: async () => ({status: true})}; };
    ew.eval(source);
    assert.equal(ed.querySelector('[data-scrum-step="selection"]').hidden, true);
    assert.equal(ed.querySelector('[data-scrum-step="sizes"]').hidden, false);
    assert.equal(ed.querySelector('[data-scrum-previous]'), null, 'No return to selection in adjustment mode');
    const estimateSelects = ed.querySelectorAll('[data-scrum-preview] select');
    assert.deepEqual(Array.from(estimateSelects, select => Number(select.dataset.projectId)), [fixture.parent, fixture.child], 'Root precedes its descendants');
    assert.equal(ed.querySelectorAll('[data-scrum-remove-tree]').length, 1, 'Only the root has a trash button');
    estimateSelects[1].value = 'L'; estimateSelects[1].dispatchEvent(new ew.Event('change', {bubbles: true}));
    ed.querySelector('[data-scrum-import]').click();
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(estimateRequests[0].get('action'), 'estimates');
    assert.equal(estimateRequests[0].get('sizes[' + fixture.child + ']'), 'L');
    ed.querySelector('[data-scrum-remove-tree]').click();
    assert.equal(ed.querySelectorAll('[data-scrum-preview] select').length, 0, 'Removing a root also removes its descendants');
    assert.equal(estimateRequests.length, 1, 'Removal stays local until saving');
    assert.equal(ed.querySelector('[data-scrum-import]').disabled, false, 'Removing the last tree can be saved');
    ed.querySelector('[data-scrum-import]').click();
    await new Promise(resolve => setImmediate(resolve));
    assert.deepEqual(estimateRequests[1].getAll('removed[]'), [String(fixture.parent)]);
    estimatesDom.window.close();

    const editorDom = new JSDOM(fixture.editor, {url: 'https://omo.test/omo/', runScripts: 'outside-only'});
    const editorWindow = editorDom.window; let saved;
    editorWindow.omoNotify = () => {};
    editorWindow.omoReplaceFetchedPanelRoot = () => Promise.resolve(null);
    editorWindow.fetch = async (url, options) => { saved = options.body; return {json: async () => ({status: true, url: '/omo/api/scrum/index.php?id=1'})}; };
    editorWindow.eval(source);
    const form = editorWindow.document.querySelector('#formulaire-edit');
    form.querySelector('[name="title"]').value = 'Sprint browser test';
    form.dispatchEvent(new editorWindow.Event('submit', {bubbles: true, cancelable: true}));
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(saved.get('title'), 'Sprint browser test'); assert.equal(saved.get('action'), 'save');
    assert.ok(saved.get('_csrf'), 'Editor must submit its session CSRF token');
    editorDom.window.close();

    const boardDom = new JSDOM(fixture.detail, {url: 'https://omo.test/omo/#scrum', runScripts: 'outside-only', pretendToBeVisual: true});
    const boardWindow = boardDom.window;
    boardWindow.resetGenericExpandedMenu = () => {};
    let reloadOptions;
    boardWindow.omoReplaceFetchedPanelRoot = options => { reloadOptions = options; return Promise.resolve(options.currentRoot); };
    boardWindow.eval(fs.readFileSync(path.join(__dirname, '../omo/api/projects/projects.js'), 'utf8'));
    await boardWindow.omoProjectsAfterSave();
    assert.equal(reloadOptions.rootSelector, '#omo-scrum-detail', 'Project saves must refresh the sprint and its chart');
    assert.match(reloadOptions.url, /\/scrum\/index.php/, 'The kanban must stay in Scrum');
    assert.equal(boardWindow.location.hash, '#scrum');
    boardDom.window.close();
    const shellDom = new JSDOM(fixture.listing, {url: 'https://omo.test/omo/#scrum', runScripts: 'outside-only', pretendToBeVisual: true});
    const shell = shellDom.window; const shellDocument = shell.document;
    const refreshes = []; const popups = [];
    shell.omoNotify = () => {};
    shell.commonRenderLoadingState = host => { host.textContent = 'Loading'; };
    shell.omoCreateSubdrawerController = ({drawer}) => ({open: () => { drawer.hidden = false; drawer.classList.add('is-open'); }});
    shell.omoReplaceFetchedPanelRoot = options => { refreshes.push(options); return Promise.resolve(options.currentRoot); };
    shell.commonTopbarOpenModal = (...args) => popups.push(args);
    shell.commonExecuteFragmentScripts = async () => { shell.eval(source); };
    shell.fetch = async () => ({ok: true, text: async () => fixture.detail});
    shell.eval(source);
    shellDocument.querySelector('[data-scrum-open]').click();
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(shellDocument.querySelector('[data-scrum-drawer]').hidden, false, 'Open sprint in a subdrawer');
    assert.ok(shellDocument.querySelector('#omo-scrum-root #omo-scrum-detail'), 'List stays behind the detail');
    assert.equal(refreshes.length, 0, 'Opening detail does not replace the list');
    shellDocument.querySelector('[data-scrum-popup]').click();
    assert.equal(popups.length, 1, 'Add projects opens the shared popup once');
    assert.equal(popups[0][2], 'fetch');
    assert.match(popups[0][1], /import=1/);
    shellDocument.querySelector('[data-scrum-close]').click();
    assert.equal(shellDocument.querySelector('[data-scrum-drawer]').hidden, true);
    assert.equal(refreshes.length, 1, 'Closing refreshes the list once');
    assert.equal(refreshes[0].rootSelector, '#omo-scrum-root');
    shellDom.window.close();
    console.log('Scrum browser estimation, import and adminEdit tests passed.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
